const RECENT_KEY = 'emoji.recent';
const RECENT_MAX = 36;

export function recentEmojis() {
  const list = prefs.get(RECENT_KEY, []);
  return Array.isArray(list) ? list : [];
}

export function noteEmojiUsed(e) {
  if (!e) return;
  prefs.set(RECENT_KEY, [e, ...recentEmojis().filter((x) => x !== e)].slice(0, RECENT_MAX));
}
